SCHEMA = """
CREATE TABLE IF NOT EXISTS users(
 id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, email TEXT UNIQUE NOT NULL,
 password_hash TEXT NOT NULL, daily_hours REAL DEFAULT 4, pref_start TEXT DEFAULT '17:00',
 break_min INTEGER DEFAULT 10, created TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS subjects(
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name TEXT NOT NULL, difficulty TEXT NOT NULL DEFAULT 'Medium', priority INTEGER NOT NULL DEFAULT 2,
 completion INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS exam_details(
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE, exam_date TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS study_tasks(
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 subject_id INTEGER REFERENCES subjects(id) ON DELETE SET NULL, title TEXT NOT NULL, deadline TEXT,
 completed INTEGER DEFAULT 0, created TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS study_schedules(
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 subject_id INTEGER REFERENCES subjects(id) ON DELETE CASCADE, date TEXT NOT NULL,
 start TEXT NOT NULL, end TEXT NOT NULL, kind TEXT DEFAULT 'study');
CREATE TABLE IF NOT EXISTS study_sessions(
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 subject_id INTEGER REFERENCES subjects(id) ON DELETE SET NULL, date TEXT NOT NULL,
 minutes INTEGER NOT NULL, kind TEXT DEFAULT 'focus');
"""
